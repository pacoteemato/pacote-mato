'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const root=path.resolve(__dirname,'..');
const ler=p=>fs.readFileSync(path.join(root,p),'utf8');
const html=ler('index.html');
const ativos=[...html.matchAll(/(?:src|href)="((?:js|css)\/[^"?]+)/g)].map(x=>x[1]);
assert.equal(new Set(ativos).size,ativos.length,'Arquivos duplicados no HTML');
for(const asset of ativos)assert.ok(fs.existsSync(path.join(root,asset)),'Arquivo ausente: '+asset);
for(const js of ativos.filter(x=>x.endsWith('.js')))new vm.Script(ler(js),{filename:js});
const app=ler('js/app.js');
assert.match(app,/cadastroFirebaseEmAndamento/);
assert.match(app,/REGISTERED:'registered'/);
assert.match(app,/const expiraEm = ativadoEm \+ \(diasTeste/);
assert.match(app,/extrairCodigosCircuitNotasFragmentadasV109/);
assert.match(app,/extrairCodigosCircuitNotasPrefixo11V110/);
const nav=ler('js/navegacao/navegacao.js');
assert.match(nav,/SOURCE_DIRECTION/);
assert.match(nav,/distanciaAtual>1200/);
assert.match(nav,/navPerspectiveBtn/);
assert.match(nav,/navVoiceVolume/);
const voice=ler('js/navegacao/voz-navegacao.js');
assert.match(voice,/definirVolume/);
assert.match(html,/id="routingAddPackagesBtn"/);
assert.match(html,/id="routingRemovePackagesBtn"/);
assert.match(html,/id="routingShareSendBtn"/);
assert.match(html,/id="routingShareReceiveBtn"/);
assert.match(html,/id="navPerspectiveBtn"/);
assert.match(html,/id="navVoiceVolume"/);
assert.match(html,/js\/partilhas\/partilhar-paradas\.js/);
console.log('PASSOU: caminhos dos arquivos, sintaxe, cadastro, PDFs Circuit, mapa, voz e botoes originais.');
